// Command reference writes the CLI and HTTP reference pages from the
// inbai usage lines and from api/openapi.yaml.
package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

func main() {
	root, err := moduleRoot()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(2)
	}
	check := len(os.Args) == 2 && os.Args[1] == "-check"
	if err := write(root, check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func moduleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("go.mod not found")
		}
		dir = parent
	}
}

func write(root string, check bool) error {
	httpPage, err := httpReference(filepath.Join(root, "api", "openapi.yaml"))
	if err != nil {
		return err
	}
	cliPage, err := cliReference(filepath.Join(root, "cmd", "inbai"))
	if err != nil {
		return err
	}
	pages := map[string]string{
		filepath.Join(root, "docs", "reference", "http.md"): httpPage,
		filepath.Join(root, "docs", "reference", "cli.md"):  cliPage,
	}
	for path, body := range pages {
		if check {
			got, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			if strings.ReplaceAll(string(got), "\r\n", "\n") != body {
				return fmt.Errorf("%s is stale; run go run ./tools/reference", filepath.Base(path))
			}
			continue
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			return err
		}
	}
	return nil
}

type operation struct {
	method  string
	path    string
	id      string
	summary string
}

func httpReference(path string) (string, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	ops, err := operations(string(raw))
	if err != nil {
		return "", err
	}
	var buf bytes.Buffer
	buf.WriteString("Status: current\n\n")
	buf.WriteString("# HTTP reference\n\n")
	buf.WriteString("Generated from [api/openapi.yaml](../../api/openapi.yaml). Do not edit this file. Run `go run ./tools/reference`.\n\n")
	buf.WriteString("| Method | Path | Operation | Summary |\n")
	buf.WriteString("| --- | --- | --- | --- |\n")
	for _, op := range ops {
		_, _ = fmt.Fprintf(&buf, "| `%s` | `%s` | `%s` | %s |\n", strings.ToUpper(op.method), op.path, op.id, op.summary)
	}
	buf.WriteString("\n")
	return buf.String(), nil
}

var methods = map[string]bool{"get": true, "post": true, "put": true, "patch": true, "delete": true}

func operations(text string) ([]operation, error) {
	var ops []operation
	var path, method, id, summary string
	flush := func() error {
		if method == "" && id == "" && summary == "" {
			return nil
		}
		if path == "" || method == "" || id == "" || summary == "" {
			return fmt.Errorf("incomplete operation %s %s %s", method, path, id)
		}
		ops = append(ops, operation{method: method, path: path, id: id, summary: summary})
		method, id, summary = "", "", ""
		return nil
	}
	for _, line := range strings.Split(strings.ReplaceAll(text, "\r\n", "\n"), "\n") {
		trim := strings.TrimSpace(line)
		if strings.HasPrefix(line, "  /") && strings.HasSuffix(trim, ":") {
			if err := flush(); err != nil {
				return nil, err
			}
			path = strings.TrimSuffix(trim, ":")
			continue
		}
		name := strings.TrimSuffix(trim, ":")
		if strings.HasPrefix(line, "    ") && !strings.HasPrefix(line, "     ") && methods[name] {
			if err := flush(); err != nil {
				return nil, err
			}
			method = name
			continue
		}
		if strings.HasPrefix(trim, "operationId:") {
			id = strings.TrimSpace(strings.TrimPrefix(trim, "operationId:"))
		}
		if strings.HasPrefix(trim, "summary:") {
			summary = strings.TrimSpace(strings.TrimPrefix(trim, "summary:"))
		}
		if id != "" && summary != "" {
			if err := flush(); err != nil {
				return nil, err
			}
		}
	}
	if err := flush(); err != nil {
		return nil, err
	}
	if len(ops) == 0 {
		return nil, fmt.Errorf("openapi has no operations")
	}
	return ops, nil
}

var usageRE = regexp.MustCompile(`"(usage: inbai[^"]*)"`)

func cliReference(dir string) (string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return "", err
	}
	seen := map[string]bool{}
	var lines []string
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") || strings.HasSuffix(entry.Name(), "_test.go") {
			continue
		}
		raw, err := os.ReadFile(filepath.Join(dir, entry.Name()))
		if err != nil {
			return "", err
		}
		for _, match := range usageRE.FindAllStringSubmatch(string(raw), -1) {
			line := strings.TrimSuffix(match[1], `\n`)
			if strings.Contains(line, "%") {
				return "", fmt.Errorf("%s: usage line has a format verb: %s", entry.Name(), line)
			}
			if seen[line] {
				continue
			}
			seen[line] = true
			lines = append(lines, line)
		}
	}
	if len(lines) == 0 {
		return "", fmt.Errorf("no usage lines in %s", dir)
	}
	sort.Strings(lines)
	var buf bytes.Buffer
	buf.WriteString("Status: current\n\n")
	buf.WriteString("# CLI reference\n\n")
	buf.WriteString("Generated from the usage lines in [cmd/inbai](../../cmd/inbai). Do not edit this file. Run `go run ./tools/reference`.\n\n")
	for _, line := range lines {
		_, _ = fmt.Fprintf(&buf, "- `%s`\n", line)
	}
	buf.WriteString("\n")
	return buf.String(), nil
}
