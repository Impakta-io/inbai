// Command reference writes the CLI and HTTP reference pages from the inbai
// and inbaid command tables and from api/openapi.yaml.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"unicode"
)

func main() {
	root, err := moduleRoot()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(2)
	}
	check := len(os.Args) == 2 && os.Args[1] == "-check"
	if err := write(root, check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func moduleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("go.mod not found")
		}
		dir = parent
	}
}

func write(root string, check bool) error {
	httpPage, err := httpReference(filepath.Join(root, "api", "openapi.yaml"))
	if err != nil {
		return err
	}
	var tables []cliTable
	for _, binary := range []string{"inbai", "inbaid"} {
		table, err := loadTable(root, binary)
		if err != nil {
			return err
		}
		tables = append(tables, table)
	}
	cliPage := cliReference(tables)
	pages := map[string]string{
		filepath.Join(root, "docs", "reference", "http.md"): httpPage,
		filepath.Join(root, "docs", "reference", "cli.md"):  cliPage,
	}
	for path, body := range pages {
		if check {
			got, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			if strings.ReplaceAll(string(got), "\r\n", "\n") != body {
				return fmt.Errorf("%s is stale; run go run ./tools/reference", filepath.Base(path))
			}
			continue
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			return err
		}
	}
	return nil
}

type operation struct {
	method  string
	path    string
	id      string
	summary string
}

func httpReference(path string) (string, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	ops, err := operations(string(raw))
	if err != nil {
		return "", err
	}
	var buf bytes.Buffer
	buf.WriteString("Status: current\n\n")
	buf.WriteString("# HTTP reference\n\n")
	buf.WriteString("Generated from [api/openapi.yaml](../../api/openapi.yaml). Do not edit this file. Run `go run ./tools/reference`.\n\n")
	buf.WriteString("| Method | Path | Operation | Summary |\n")
	buf.WriteString("| --- | --- | --- | --- |\n")
	for _, op := range ops {
		_, _ = fmt.Fprintf(&buf, "| `%s` | `%s` | `%s` | %s |\n", strings.ToUpper(op.method), op.path, op.id, op.summary)
	}
	buf.WriteString("\n")
	return buf.String(), nil
}

var methods = map[string]bool{"get": true, "post": true, "put": true, "patch": true, "delete": true}

func operations(text string) ([]operation, error) {
	var ops []operation
	var path, method, id, summary string
	flush := func() error {
		if method == "" && id == "" && summary == "" {
			return nil
		}
		if path == "" || method == "" || id == "" || summary == "" {
			return fmt.Errorf("incomplete operation %s %s %s", method, path, id)
		}
		ops = append(ops, operation{method: method, path: path, id: id, summary: summary})
		method, id, summary = "", "", ""
		return nil
	}
	for _, line := range strings.Split(strings.ReplaceAll(text, "\r\n", "\n"), "\n") {
		trim := strings.TrimSpace(line)
		if strings.HasPrefix(line, "  /") && strings.HasSuffix(trim, ":") {
			if err := flush(); err != nil {
				return nil, err
			}
			path = strings.TrimSuffix(trim, ":")
			continue
		}
		name := strings.TrimSuffix(trim, ":")
		if strings.HasPrefix(line, "    ") && !strings.HasPrefix(line, "     ") && methods[name] {
			if err := flush(); err != nil {
				return nil, err
			}
			method = name
			continue
		}
		if strings.HasPrefix(trim, "operationId:") {
			id = strings.TrimSpace(strings.TrimPrefix(trim, "operationId:"))
		}
		if strings.HasPrefix(trim, "summary:") {
			summary = strings.TrimSpace(strings.TrimPrefix(trim, "summary:"))
		}
		if id != "" && summary != "" {
			if err := flush(); err != nil {
				return nil, err
			}
		}
	}
	if err := flush(); err != nil {
		return nil, err
	}
	if len(ops) == 0 {
		return nil, fmt.Errorf("openapi has no operations")
	}
	return ops, nil
}

// cliTable is what "<binary> help --json" prints. It mirrors cli.Reference in
// cmd/internal/cli, which this tool cannot import from outside cmd.
type cliTable struct {
	Program  string       `json:"program"`
	Summary  string       `json:"summary"`
	Commands []cliCommand `json:"commands"`
}

type cliCommand struct {
	Name        string   `json:"name"`
	Summary     string   `json:"summary"`
	Group       bool     `json:"group"`
	Usage       []string `json:"usage"`
	Description string   `json:"description"`
	Flags       string   `json:"flags"`
	Positional  bool     `json:"positional"`
	Env         []cliEnv `json:"env"`
	Examples    []string `json:"examples"`
}

type cliEnv struct {
	Group   string `json:"group"`
	Name    string `json:"name"`
	Text    string `json:"text"`
	Default string `json:"default"`
}

// loadTable runs "<binary> help --json" from source. A package main cannot be
// imported, so the table is read through the binary's own help.
func loadTable(root, binary string) (cliTable, error) {
	cmd := exec.Command("go", "run", "./cmd/"+binary, "help", "--json")
	cmd.Dir = root
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if err != nil {
		return cliTable{}, fmt.Errorf("%s help --json: %v\n%s", binary, err, stderr.String())
	}
	var table cliTable
	if err := json.Unmarshal(out, &table); err != nil {
		return cliTable{}, fmt.Errorf("%s help --json: %v", binary, err)
	}
	if table.Program != binary || len(table.Commands) == 0 {
		return cliTable{}, fmt.Errorf("%s help --json has no commands", binary)
	}
	return table, nil
}

func cliReference(tables []cliTable) string {
	var buf bytes.Buffer
	buf.WriteString("Status: current\n\n")
	buf.WriteString("# CLI reference\n\n")
	buf.WriteString("Generated from the command tables in [cmd/inbai/commands.go](../../cmd/inbai/commands.go) and [cmd/inbaid/commands.go](../../cmd/inbaid/commands.go). Do not edit this file. Run `go run ./tools/reference`.\n\n")
	buf.WriteString("In a terminal, `inbai help <command>` and `inbaid help <command>` print the same text, and so does `--help` after any command.\n\n")
	for _, table := range tables {
		_, _ = fmt.Fprintf(&buf, "## %s\n\n%s\n\n", table.Program, prose(table.Summary))
		buf.WriteString("| Command | Summary |\n| --- | --- |\n")
		for _, c := range table.Commands {
			full := table.Program + " " + c.Name
			_, _ = fmt.Fprintf(&buf, "| [`%s`](#%s) | %s |\n", full, slug(full), cell(c.Summary))
		}
		buf.WriteString("\n")
		for _, c := range table.Commands {
			writeCommand(&buf, table.Program, c)
		}
	}
	return strings.TrimRight(buf.String(), "\n") + "\n"
}

func writeCommand(buf *bytes.Buffer, program string, c cliCommand) {
	_, _ = fmt.Fprintf(buf, "### %s %s\n\n%s.\n\n", program, c.Name, prose(c.Summary))
	if len(c.Usage) > 0 {
		_, _ = fmt.Fprintf(buf, "```text\n%s\n```\n\n", strings.Join(c.Usage, "\n"))
	}
	for _, para := range strings.Split(strings.TrimSpace(c.Description), "\n\n") {
		if para = strings.TrimSpace(para); para != "" {
			_, _ = fmt.Fprintf(buf, "%s\n\n", prose(para))
		}
	}
	if c.Group {
		_, _ = fmt.Fprintf(buf, "Run `%s help %s <command>` for one of its subcommands.\n\n", program, c.Name)
	}
	if c.Flags != "" {
		_, _ = fmt.Fprintf(buf, "Flags:\n\n```text\n%s```\n\n", c.Flags)
		if c.Positional {
			buf.WriteString("Flags go before arguments. Flag parsing stops at the first argument.\n\n")
		}
	}
	if len(c.Env) > 0 {
		buf.WriteString("Environment:\n\n| Variable | Meaning | Default |\n| --- | --- | --- |\n")
		for _, v := range c.Env {
			meaning := v.Text
			if v.Group != "" {
				meaning = v.Group + ": " + meaning
			}
			def := ""
			if v.Default != "" {
				def = cell(v.Default)
			}
			_, _ = fmt.Fprintf(buf, "| `%s` | %s | %s |\n", v.Name, cell(meaning), def)
		}
		buf.WriteString("\n")
	}
	if len(c.Examples) > 0 {
		_, _ = fmt.Fprintf(buf, "Examples:\n\n```sh\n%s\n```\n\n", strings.Join(c.Examples, "\n"))
	}
}

// prose escapes the characters Markdown would read as HTML or emphasis.
var prose = strings.NewReplacer("<", "&lt;", ">", "&gt;", "*", `\*`).Replace

func cell(text string) string {
	return strings.ReplaceAll(prose(text), "|", `\|`)
}

// slug is the anchor of a heading, computed as tools/docscheck computes it.
func slug(title string) string {
	var b strings.Builder
	hyphen := false
	for _, r := range strings.ToLower(title) {
		if unicode.IsLetter(r) || unicode.IsDigit(r) || r == '_' {
			b.WriteRune(r)
			hyphen = false
			continue
		}
		if (r == ' ' || r == '-') && b.Len() > 0 && !hyphen {
			b.WriteByte('-')
			hyphen = true
		}
	}
	return strings.TrimRight(b.String(), "-")
}
